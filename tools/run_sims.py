#!/usr/bin/env python3
"""
Reference SPICE runs for EEEN20020 Experiment 2 (audio amplifier).

Runs ngspice (NOT LTspice) on the exact circuit described in the LTspice
files in spice/ltspice, using the same uA741 macromodel, and writes:

  spice/ngspice/*.cir        generated decks (re-runnable by hand)
  spice/results/*.csv        waveform / sweep data used for the figures
  spice/results/summary.json every number quoted in the prototype report

Every number produced here is a SIMULATION result from ngspice. The report
labels it as such; the student must replace it with their own LTspice output.
"""
import json
import math
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NGDIR = os.path.join(ROOT, "spice", "ngspice")
RESDIR = os.path.join(ROOT, "spice", "results")
LIB = "../ltspice/uA741.lib"

# ---------------------------------------------------------------- design ---
NOMINAL = dict(R1MIN=1e-3, R1MAX=50e3, R2=10e3, R3=10e3, VS=5.0)
# Hypothetical "measured" component values used ONLY to demonstrate Section G.
# They are NOT measurements. Replace with real DMM readings.
PROTO_MEAS = dict(R1MIN=35.0, R1MAX=47.62e3, R2=9.93e3, R3=9.97e3, VS=5.0)


def circuit(r1, r2, r3, vs=5.0, src="DC 0", rload=None, rs=None, open_input=False):
    """Netlist body. Node names match the LTspice schematics.
    rs         : source resistance of the generator (None = ideal source)
    open_input : True = signal source unplugged (only R3 holds the input node)
    """
    lines = [
        f".include {LIB}",
        ".options savecurrents",
        f"VCC vcc 0 DC {vs}",
        f"VEE vee 0 DC {-vs}",
    ]
    if open_input:
        pass
    elif rs is None:
        lines.append(f"VIN in 0 {src}")
    else:
        lines += [f"VIN src 0 {src}", f"RS src in {rs}"]
    lines += [
        f"R3 in 0 {r3}",
        f"R1 out inv {r1}",
        f"R2 inv 0 {r2}",
        "XU1 in inv vcc vee oa uA741",
        # 0 V ammeter so the op-amp output-pin current is reported directly
        "VIOUT oa out DC 0",
    ]
    if rload is not None:
        lines.append(f"RL out 0 {rload}")
    return "\n".join(lines)


def run_deck(name, body, control):
    path = os.path.join(NGDIR, name + ".cir")
    with open(path, "w") as f:
        f.write(f"* {name} -- generated by tools/run_sims.py (ngspice)\n")
        f.write(body + "\n.control\n" + control + "\n.endc\n.end\n")
    out = subprocess.run(["ngspice", "-b", name + ".cir"], cwd=NGDIR,
                         capture_output=True, text=True)
    log = out.stdout + out.stderr
    with open(os.path.join(NGDIR, name + ".log"), "w") as f:
        f.write(log)
    if out.returncode != 0 or "error" in log.lower() and "no error" not in log.lower():
        # ngspice prints benign 'warning' lines; only hard errors stop us
        if re.search(r"(?im)^\s*error", log):
            print(log)
            sys.exit(f"ngspice failed on {name}")
    return log


def grab(log, key):
    """Return float value of 'key = value' printed by ngspice."""
    m = re.search(rf"(?im)^\s*{re.escape(key)}\s*=\s*([-+0-9.eE]+)", log)
    if not m:
        raise KeyError(f"{key} not found")
    return float(m.group(1))


OP_VECS = ["v(in)", "v(inv)", "v(out)", "@r1[i]", "@r2[i]", "@r3[i]",
           "i(viout)", "i(vcc)", "i(vee)"]


def op_point(tag, p, r1, vin_dc, open_input=False, r3=None):
    body = circuit(r1, p["R2"], p["R3"] if r3 is None else r3, p["VS"],
                   src=f"DC {vin_dc}", open_input=open_input)
    ctrl = ["op"]
    for i, v in enumerate(OP_VECS):
        ctrl.append(f"let q{i} = {v}")
        ctrl.append(f'echo "q{i} = $&q{i}"')
    log = run_deck(tag, body, "\n".join(ctrl))
    vals = {v: grab(log, f"q{i}") for i, v in enumerate(OP_VECS)}
    return vals


def tran(tag, p, r1, vpk, f=1e3, rload=None, tstop=6e-3, save_csv=True, vs=None,
         rs=None):
    vs = p["VS"] if vs is None else vs
    body = circuit(r1, p["R2"], p["R3"], vs, src=f"DC 0 SIN(0 {vpk} {f})",
                   rload=rload, rs=rs)
    t_meas0 = 2e-3
    pk_t = 4.25e-3  # positive peak of the input (sin, 1 kHz)
    nk_t = 4.75e-3  # negative peak
    ctrl = [
        "tran 2.5u {:g} 0 0.5u".format(tstop),    # 0.5 us internal step, 2.5 us print step (lands on peaks)
        f"meas tran vinpp pp v(in) from={t_meas0} to={tstop}",
        f"meas tran voutpp pp v(out) from={t_meas0} to={tstop}",
        f"meas tran vinrms rms v(in) from={t_meas0} to={tstop}",
        f"meas tran voutrms rms v(out) from={t_meas0} to={tstop}",
        f"meas tran voutmax max v(out) from={t_meas0} to={tstop}",
        f"meas tran voutmin min v(out) from={t_meas0} to={tstop}",
        f"meas tran ioutmax max i(viout) from={t_meas0} to={tstop}",
    ]
    for lab, t in (("pk", pk_t), ("nk", nk_t)):
        for i, v in enumerate(OP_VECS):
            ctrl.append(f"meas tran {lab}{i} find {v} at={t}")
    if save_csv:
        csv = os.path.join(RESDIR, tag + ".csv").replace(ROOT + "/", "../../")
        ctrl.append("set wr_singlescale")
        ctrl.append("set wr_vecnames")
        ctrl.append("linearize v(in) v(inv) v(out) @r1[i] @r2[i] @r3[i] i(viout)")
        ctrl.append(f"wrdata {csv} v(in) v(inv) v(out) @r1[i] @r2[i] @r3[i] i(viout)")
    log = run_deck(tag, body, "\n".join(ctrl))
    r = {k: grab(log, k) for k in ("vinpp", "voutpp", "vinrms", "voutrms",
                                   "voutmax", "voutmin", "ioutmax")}
    r["gain_pp"] = r["voutpp"] / r["vinpp"]
    r["gain_rms"] = r["voutrms"] / r["vinrms"]
    for lab in ("pk", "nk"):
        r[lab] = {v: grab(log, f"{lab}{i}") for i, v in enumerate(OP_VECS)}
    return r


def ac(tag, p, r1, rload=None):
    body = circuit(r1, p["R2"], p["R3"], p["VS"], src="DC 0 AC 1", rload=rload)
    csv = os.path.join(RESDIR, tag + ".csv").replace(ROOT + "/", "../../")
    ctrl = [
        "ac dec 200 1 10meg",
        "let g = vm(out)/vm(in)",
        "let ph = 180/pi*cph(v(out))",
        "meas ac g1k find g at=1k",
        "meas ac ph1k find ph at=1k",
        "meas ac g20k find g at=20k",
        "meas ac g10 find g at=10",
        "let g3 = g10/sqrt(2)",
        "meas ac f3db when g=g3 fall=1",
        "set wr_singlescale",
        "set wr_vecnames",
        f"wrdata {csv} g ph",
    ]
    log = run_deck(tag, body, "\n".join(ctrl))
    return {k: grab(log, k) for k in ("g1k", "ph1k", "g20k", "g10", "f3db")}


def main():
    os.makedirs(RESDIR, exist_ok=True)
    S = {"simulator": None, "nominal": NOMINAL, "proto_measured_values": PROTO_MEAS}
    ver = subprocess.run(["ngspice", "-v"], capture_output=True, text=True).stdout
    S["simulator"] = " ".join(ver.split()[:6]) if ver else "ngspice"

    n = NOMINAL
    # ---- Section B: nominal design -------------------------------------
    for cfg, r1 in (("min", n["R1MIN"]), ("max", n["R1MAX"])):
        S[f"op_bias_{cfg}"] = op_point(f"op_bias_{cfg}", n, r1, 0.0)
        S[f"op_peak_{cfg}"] = op_point(f"op_peak_{cfg}", n, r1, 0.5)
        S[f"tran1vpp_{cfg}"] = tran(f"tran1vpp_{cfg}", n, r1, 0.5)
        S[f"tran100mvpp_{cfg}"] = tran(f"tran100mvpp_{cfg}", n, r1, 0.05)
        S[f"ac_{cfg}"] = ac(f"ac_{cfg}", n, r1)
        S[f"ac_{cfg}_32ohm"] = ac(f"ac_{cfg}_32ohm", n, r1, rload=32)

    # ---- Why R3 exists: input source unplugged / AC-coupled ---------------
    S["op_bias_open_R3"] = op_point("op_bias_open_R3", n, n["R1MAX"], 0.0,
                                    open_input=True)
    S["op_bias_open_noR3"] = op_point("op_bias_open_noR3", n, n["R1MAX"], 0.0,
                                      open_input=True, r3=1e12)
    # ---- 50-ohm generator source resistance -------------------------------
    S["tran1vpp_max_rs50"] = tran("tran1vpp_max_rs50", n, n["R1MAX"], 0.5,
                                  rs=50, save_csv=False)
    # ---- Pitfall: generator left in 50-ohm mode => ~2 Vpp at the input --
    S["tran2vpp_max_clip"] = tran("tran2vpp_max_clip", n, n["R1MAX"], 1.0)
    # ---- Headphone-like load with bench-signal amplitude (160 mVpp) ------
    S["tran160m_max_32ohm"] = tran("tran160m_max_32ohm", n, n["R1MAX"], 0.08,
                                   rload=32)
    # ---- Supply sensitivity: +/-4.75 V and +/-5.25 V -----------------------
    for vs in (4.75, 5.25):
        S[f"tran1vpp_max_vs{vs}"] = tran(f"tran1vpp_max_vs{vs}", n, n["R1MAX"],
                                         0.5, vs=vs, save_csv=False)

    # ---- Section G demo: HYPOTHETICAL 'measured' values ------------------
    m = PROTO_MEAS
    for cfg, r1 in (("min", m["R1MIN"]), ("max", m["R1MAX"])):
        S[f"G_op_peak_{cfg}"] = op_point(f"G_op_peak_{cfg}", m, r1, 0.5)
        S[f"G_tran1vpp_{cfg}"] = tran(f"G_tran1vpp_{cfg}", m, r1, 0.5)

    with open(os.path.join(RESDIR, "summary.json"), "w") as f:
        json.dump(S, f, indent=2)

    # ---- console digest -------------------------------------------------
    def g(k):
        return S[k]["gain_pp"]
    print("Simulator:", S["simulator"])
    print(f"Nominal 1Vpp   : AVmin={g('tran1vpp_min'):.5f}  AVmax={g('tran1vpp_max'):.5f}")
    print(f"Nominal 100mVpp: AVmin={g('tran100mvpp_min'):.5f}  AVmax={g('tran100mvpp_max'):.5f}")
    for c in ("min", "max"):
        a = S[f"ac_{c}"]
        print(f"AC {c}: g1k={a['g1k']:.5f} ph1k={a['ph1k']:.3f} deg  f3dB={a['f3db']/1e3:.1f} kHz  g20k={a['g20k']:.5f}")
        a = S[f"ac_{c}_32ohm"]
        print(f"AC {c} 32ohm: g1k={a['g1k']:.5f}  g20k={a['g20k']:.5f} f3dB={a['f3db']/1e3:.1f} kHz")
    c = S["tran2vpp_max_clip"]
    print(f"2Vpp @max: voutpp={c['voutpp']:.3f}  max={c['voutmax']:.3f} min={c['voutmin']:.3f}  'gain'={c['gain_pp']:.3f}")
    h = S["tran160m_max_32ohm"]
    print(f"160mVpp @max, 32ohm: gain={h['gain_pp']:.4f}  Iout,max={h['ioutmax']*1e3:.2f} mA")
    for vs in (4.75, 5.25):
        print(f"Vs=+/-{vs}: AVmax={g(f'tran1vpp_max_vs{vs}'):.5f}")
    print(f"G (hypothetical R): AVmin={g('G_tran1vpp_min'):.5f} AVmax={g('G_tran1vpp_max'):.5f}")
    r = S["tran1vpp_max_rs50"]
    print(f"Rs=50: vinpp={r['vinpp']:.5f} voutpp={r['voutpp']:.5f} gain={r['gain_pp']:.5f}")
    for k in ("op_bias_min", "op_bias_max", "op_peak_min", "op_peak_max",
              "op_bias_open_R3", "op_bias_open_noR3"):
        print(k, {kk: f"{vv:.4e}" for kk, vv in S[k].items()})


if __name__ == "__main__":
    main()
